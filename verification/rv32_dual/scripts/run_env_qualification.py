"""Usage (from verification/rv32_dual): python scripts/run_env_qualification.py [--force]"""
import argparse
import datetime
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "env", "qual"))
import qual_env  # noqa: E402


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def wj(path, obj, force):
    if os.path.exists(path) and not force:
        raise SystemExit("refusing to overwrite %s (use --force)" % path)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")
    return sha(path)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args(argv)
    out = os.path.join(ROOT, "docs", "02_env")
    os.makedirs(out, exist_ok=True)
    cmd = "python scripts/run_env_qualification.py" + (" --force" if a.force else "")
    summary, ok_all = [], True
    for sid, (fn, srcs) in qual_env.SUITES.items():
        s = fn()
        d = os.path.join(out, sid)
        os.makedirs(d, exist_ok=True)
        man = {"label": "AI-generated qualification manifest; review pending", "checker_id": sid,
               "sources": [{"path": p, "sha256": sha(os.path.join(ROOT, p))} for p in srcs + ["env/qual/qual_env.py"]],
               "correlated_error_note": "Synthetic logs and the checker were written by the same AI author from models/README.md; "
                                        "faults injected are hand-chosen defect classes, not an exhaustive mutation set."}
        msha = wj(os.path.join(d, "build_manifest.json"), man, a.force)
        tests, counts = [], {}
        for k in ("fault_detection", "known_answer", "boundary", "negative", "reset"):
            cases = s.cases[k]
            if not cases:
                tests.append({"kind": k, "status": "not_applicable", "command": cmd, "exit_code": None, "expected": "n/a",
                              "observed": s.na.get(k, "no cases"), "evidence": None})
                counts[k] = (0, 0)
                continue
            n = sum(c["pass"] for c in cases)
            counts[k] = (n, len(cases))
            ok = n == len(cases)
            ok_all &= ok
            esha = wj(os.path.join(d, "qualification_%s.json" % k), {"checker_id": sid, "kind": k, "cases": cases}, a.force)
            tests.append({"kind": k, "status": "pass" if ok else "fail", "command": cmd, "exit_code": 0 if ok else 1,
                          "expected": "detected" if k == "fault_detection" else "match",
                          "observed": "%d/%d" % (n, len(cases)),
                          "evidence": {"path": "docs/02_env/%s/qualification_%s.json" % (sid, k), "sha256": esha}})
        wj(os.path.join(d, "%s.qualification.json" % sid), {"checker_id": sid, "label": "AI-generated qualification record; not human-reviewed",
                                                           "build_manifest_sha256": msha,
                                                           "review": {"decision": "pending", "approver": "pending", "date": None},
                                                           "tests": tests}, a.force)
        f = lambda k: "%d/%d" % counts[k] if counts[k][1] else "n/a"
        print("%-16s KAT %s  boundary %s  negative %s  reset %s  faults detected %s" % (sid, f("known_answer"), f("boundary"), f("negative"), f("reset"), f("fault_detection")))
        summary.append({"id": sid, "counts": {k: list(v) for k, v in counts.items()}})
    wj(os.path.join(out, "summary.json"), {"date": datetime.date.today().isoformat(), "command": cmd, "suites": summary,
                                          "overall": "pass" if ok_all else "fail", "review": "pending"}, a.force)
    md = ["# Environment checker qualification summary", "", "AI-generated by `%s`; synthetic NDJSON logs; human review pending." % cmd, "",
          "| Checker | KAT | Boundary | Negative | Reset | Injected faults detected |", "|---|---|---|---|---|---|"]
    for x in summary:
        c = x["counts"]
        g = lambda k: "%d/%d" % tuple(c[k]) if c[k][1] else "n/a"
        md.append("| %s | %s | %s | %s | %s | %s |" % (x["id"], g("known_answer"), g("boundary"), g("negative"), g("reset"), g("fault_detection")))
    p = os.path.join(out, "summary.md")
    if os.path.exists(p) and not a.force:
        raise SystemExit("refusing to overwrite %s" % p)
    open(p, "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("OVERALL: %s (%d suites)" % ("PASS" if ok_all else "FAIL", len(summary)))
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
