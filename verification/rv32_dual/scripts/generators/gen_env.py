def debug_rom_source():
    """Q-G0-07 A: park loop at HaltAddress 0x800 that writes a per-hart halted flag,
    waits for a per-hart resume flag and returns with dret; ExceptionAddress 0x808
    records a debug-mode exception flag and parks. Flags live in the testbench
    MMIO control window (env/README.md): HALTED 0x10000400+4*hart,
    RESUME 0x10000300+4*hart, DBG_EXC 0x10000500+4*hart."""
    return """# AI-GENERATED debug ROM (Q-G0-07 A); base 0x800 = RV32 HDS 8.2 HaltAddress
        j    halt_entry                 # 0x800 HaltAddress
        nop                             # 0x804
exc_entry:                              # 0x808 ExceptionAddress
        csrw dscratch0, t0
        csrw dscratch1, t1
        csrr t0, mhartid
        slli t0, t0, 2
        lui  t1, 0x10000
        add  t1, t1, t0                 # t1 = 0x10000000 + 4*hart
        li   t0, 1
        sw   t0, 0x500(t1)              # DBG_EXC[hart] = 1
exc_park:
        j    exc_park
halt_entry:
        csrw dscratch0, t0
        csrw dscratch1, t1
        csrr t0, mhartid
        slli t0, t0, 2
        lui  t1, 0x10000
        add  t1, t1, t0                 # t1 = 0x10000000 + 4*hart
        li   t0, 1
        sw   t0, 0x400(t1)              # HALTED[hart] = 1
wait_resume:
        lw   t0, 0x300(t1)              # RESUME[hart]
        beqz t0, wait_resume
        sw   zero, 0x300(t1)            # consume the resume request
        sw   zero, 0x400(t1)            # HALTED[hart] = 0
        csrr t0, dscratch0
        csrr t1, dscratch1
        dret
"""


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args(argv)
    files = gen_files()
    diffs, manifest = [], {"generator": "scripts/generators/gen_env.py",
                           "generator_sha256": sha(open(os.path.abspath(__file__), "rb").read()),
                           "inputs": [{"path": "doc/specification/VLSIT_RISCV_DUAL_QUAD_CPU_CLUSTER_HDS.md", "sha256": sha(open(HDS, "rb").read())},
                                      {"path": "verification/rv32_dual/models/asm_rv32/asm_rv32.py",
                                       "sha256": sha(open(os.path.join(ROOT, "models", "asm_rv32", "asm_rv32.py"), "rb").read())}],
                           "command": "python scripts/generators/gen_env.py --force", "outputs": []}
    for rel, text in sorted(files.items()):
        p = os.path.join(ROOT, rel)
        data = text.encode("utf-8")
        manifest["outputs"].append({"path": rel, "sha256": sha(data)})
        old = open(p, "rb").read() if os.path.exists(p) else None
        if old != data:
            diffs.append(rel)
            if not a.check:
                if old is not None and not a.force:
                    raise SystemExit("refusing to overwrite changed %s (use --force)" % rel)
                os.makedirs(os.path.dirname(p), exist_ok=True)
                open(p, "wb").write(data)
    if a.check:
        print("CHECK: %s" % ("identical" if not diffs else "DIFF in " + ", ".join(diffs)))
        return 1 if diffs else 0
    mp = os.path.join(ROOT, "env", "generated", "generation_manifest.json")
    with open(mp, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=1)
        f.write("\n")
    print("GENERATED %d files (%d changed)" % (len(files), len(diffs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
