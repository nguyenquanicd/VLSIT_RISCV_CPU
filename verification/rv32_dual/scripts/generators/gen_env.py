# PMU defaults REF-001 8.1 (16 counters, 64 bits); 3-bit event count (REF-001 8.3.2 "three count bits");
# 32-bit IRQ field and CSR word (workbook AXIL_QUEUED [31:0] fields).
FV_PARAMS = {"PARA_PMU_CNT_NUM": 16, "PARA_PMU_CNT_W": 64, "LPARA_EVT_COUNT_W": 3, "LPARA_IRQ_FIELD_W": 32,
             "LPARA_CSR_WORD_W": 32}


def component_stubs():
    """Lint-only stubs of the formal target components from their REF-001 14.4 port tables."""
    lines = open(HDS, encoding="utf-8").read().splitlines()
    out = [HEADER.replace("Section 6.2", "Section 14.4"),
           "// LINT-ONLY STUBS of formal target components (port lists from REF-001 14.4); no behaviour.\n",
           "/* verilator lint_off UNUSEDSIGNAL */\n/* verilator lint_off UNUSEDPARAM */\n/* verilator lint_off DECLFILENAME */\n"
           "/* verilator lint_off MULTITOP */\n"]
    for comp in FV_COMPONENTS:
        start = next(i for i, l in enumerate(lines) if l.startswith("#### 14.4.") and ("`%s`" % comp) in l)
        ports = []
        for l in lines[start + 1:]:
            if l.startswith("#### "):
                break
            m = re.match(r"^\| (input|output) \| `(?:wire|logic) (\[[^`]*\] )?(\w+)` \|$", l)
            if m:
                ports.append((m.group(1), (m.group(2) or "").strip(), m.group(3)))
        used = sorted(k for k in FV_PARAMS if any(k in w for _, w, _ in ports))
        params = ",\n".join("  parameter int %s = %d" % (k, FV_PARAMS[k]) for k in used)
        if comp == "m_vlsit_riscv_addr_decode":
            # ASSUMPTION (recorded in t_rv32d_fv_addr_decode): the decoder takes the TOP region parameter set of
            # REF-001 rev 0.40 14.4.20 under the same names; 14.4.13 lists its ports only. A mismatch fails elaboration.
            params = ",\n".join([
                "  parameter logic [31:0] PARA_ADDR_REGION_NUM = 32'd1",
                "  parameter logic [31:0] PARA_ADDR_REGION_BASE_LO [0:15] = '{0:32'h8000_0000, default:32'd0}",
                "  parameter logic [31:0] PARA_ADDR_REGION_BASE_HI [0:15] = '{default:32'd0}",
                "  parameter logic [31:0] PARA_ADDR_REGION_SIZE_LO [0:15] = '{0:32'h4000_0000, default:32'd0}",
                "  parameter logic [31:0] PARA_ADDR_REGION_SIZE_HI [0:15] = '{default:32'd0}",
                "  parameter logic [31:0] PARA_ADDR_REGION_TYPE [0:15] = '{default:32'd0}"])
        out.append("module %s %s(\n" % (comp, ("#(\n%s\n) " % params) if params else ""))
        decl = []
        for d, w, n in ports:
            decl.append("  %s %s%s" % ("input  wire " if d == "input" else "output logic", (w + " ") if w else "", n))
        out.append(",\n".join(decl) + "\n);\n")
        for d, w, n in ports:
            if d == "output":
                out.append("  assign %s = '0;\n" % n)
        out.append("endmodule\n\n")
    out.append("/* verilator lint_on MULTITOP */\n/* verilator lint_on DECLFILENAME */\n/* verilator lint_on UNUSEDPARAM */\n/* verilator lint_on UNUSEDSIGNAL */\n")
    return "".join(out)


