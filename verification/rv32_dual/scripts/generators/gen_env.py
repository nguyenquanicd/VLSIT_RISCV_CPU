def sha(b):
    return hashlib.sha256(b).hexdigest()


def parse_ports():
    lines = open(HDS, encoding="utf-8").read().splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("### 6.2 Complete AXI-profile port list"))
    ports = []
    for l in lines[start:]:
        if l.startswith("### 6.3"):
            break
        m = re.match(r"^\| `(\w+)` \| (input|output) \| `([^`]+)` \|", l)
        if m:
            w = m.group(3)
            ports.append({"name": m.group(1), "dir": m.group(2), "width": "" if w == "1" else w})
    if len(ports) != 111:
        raise SystemExit("expected 111 ports in REF-001 6.2, parsed %d" % len(ports))
    return ports


def sv_width(w):
    w = w.replace("PARA_CPU_NUM", "CPU_NUM").replace("PARA_AXI_MEM_DATA_W", "MEM_DW")
    return (w + " ") if w else ""


def gen_files():
    ports = parse_ports()
    out = {}
    out["tb/generated/dut_ports.json"] = json.dumps({"source": "REF-001 rev 0.39 Section 6.2", "ports": ports}, indent=1) + "\n"
    conn = [HEADER]
    for i, p in enumerate(ports):
        conn.append("    .%s(%s)%s\n" % (p["name"], p["name"], "," if i < len(ports) - 1 else ""))
    out["tb/generated/dut_port_connect.svh"] = "".join(conn)
    decl = [HEADER, "// tb-side nets, one per DUT port (CPU_NUM, MEM_DW are tb localparams)\n"]
    for p in ports:
        decl.append("logic %s%s;\n" % (sv_width(p["width"]), p["name"]))
    out["tb/generated/dut_signals.svh"] = "".join(decl)
    st = [HEADER, "// LINT-ONLY STUB with the REF-001 6.2 port list; it models no behaviour and is never a DUT.\n",
          "/* verilator lint_off UNUSEDSIGNAL */\n/* verilator lint_off UNUSEDPARAM */\n/* verilator lint_off DECLFILENAME */\n",
          "module m_vlsit_riscv_cluster_axi_top #(\n  parameter int PARA_CPU_NUM = 4,\n  parameter int PARA_TIMING_PROFILE = 0,\n"
          "  parameter int PARA_AXI_MEM_DATA_W = 64,\n"
          "  // REF-001 rev 0.40 Section 14.4.20 TOP address-region parameters (declarations and defaults as specified)\n"
          "  parameter logic [31:0] PARA_ADDR_REGION_NUM = 32'd1,\n"
          "  parameter logic [31:0] PARA_ADDR_REGION_BASE_LO [0:15] = '{0:32'h8000_0000, default:32'd0},\n"
          "  parameter logic [31:0] PARA_ADDR_REGION_BASE_HI [0:15] = '{default:32'd0},\n"
          "  parameter logic [31:0] PARA_ADDR_REGION_SIZE_LO [0:15] = '{0:32'h4000_0000, default:32'd0},\n"
          "  parameter logic [31:0] PARA_ADDR_REGION_SIZE_HI [0:15] = '{default:32'd0},\n"
          "  parameter logic [31:0] PARA_ADDR_REGION_TYPE [0:15] = '{default:32'd0}\n) (\n"]
    for i, p in enumerate(ports):
        w = p["width"]
        kind = "input  wire " if p["dir"] == "input" else "output logic "
        st.append("  %s%s%s%s\n" % (kind, (w + " ") if w else "", p["name"], "," if i < len(ports) - 1 else ""))
    st.append(");\n")
    for p in ports:
        if p["dir"] == "output":
            st.append("  assign %s = '0;\n" % p["name"])
    st.append("endmodule\n/* verilator lint_on UNUSEDPARAM */\n/* verilator lint_on UNUSEDSIGNAL */\n")
    out["tb/generated/m_vlsit_riscv_cluster_axi_top_stub.sv"] = "".join(st)
    out["tb/generated/fv_component_stubs.sv"] = component_stubs()
    out["tb/generated/region_params.svh"] = region_params()
